import { chromium, expect } from '@playwright/test';
import pg from 'pg';
import bcrypt from 'bcryptjs';
import { randomBytes } from 'node:crypto';
import { readFile } from 'node:fs/promises';
import type { Server } from 'node:http';

// Browser checks use their own schema, never the application's saved data.
const url = new URL(process.env.TEST_DATABASE_URL || 'postgresql://127.0.0.1:55432/quecare');
const root = new pg.Pool({ connectionString: url.toString() });
const schema = 'browser_units_' + randomBytes(6).toString('hex');
let server: Server | undefined, db: pg.Pool | undefined;
let browser: Awaited<ReturnType<typeof chromium.launch>> | undefined;
try {
  await root.query(`CREATE SCHEMA ${schema}`);
  url.searchParams.set('options', `-c search_path=${schema}`);
  process.env.DATABASE_URL = url.toString(); process.env.NODE_ENV = 'test'; process.env.DEMO_MODE = 'false';
  db = (await import('../server/db')).pool;
  await db.query(await readFile(new URL('../server/schema.sql', import.meta.url), 'utf8'));
  const hash = await bcrypt.hash('TestPassword123!', 4);
  await db.query("INSERT INTO users(name,email,password_hash,role) VALUES('Browser Admin','units-admin@test.local',$1,'system_admin')", [hash]);
  const { app } = await import('../server/app');
  server = app.listen(0, '127.0.0.1');
  await new Promise<void>(resolve => server!.on('listening', resolve));
  const origin = `http://127.0.0.1:${(server.address() as { port: number }).port}`;
  process.env.APP_URL = origin;
  browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
  const page = await browser.newPage();
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto(origin);
  await expect(page.getByRole('heading', { name: 'No Health Units configured', level: 1 })).toBeVisible();
  await page.getByRole('button', { name: 'Sign in / Register' }).click();
  await page.getByLabel('Email address').fill('units-admin@test.local');
  await page.getByLabel('Password', { exact: true }).fill('TestPassword123!');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  async function create(name: string) {
    await page.getByRole('button', { name: 'Add Health Unit', exact: true }).click();
    await page.getByLabel('Health Unit name').fill(name);
    await page.getByLabel('Address', { exact: true }).fill('Test address');
    await page.getByLabel('Announcement', { exact: true }).fill('Original announcement');
    await page.getByRole('button', { name: 'Create Health Unit', exact: true }).click();
    await expect(page.getByRole('dialog')).toHaveCount(0);
  }
  async function openUnits() {
    await page.getByRole('button', { name: 'Administration', exact: true }).click();
    await page.getByRole('button', { name: 'Health Units', exact: true }).click();
  }
  await create('First Health Unit');
  await expect(page.getByRole('combobox', { name: 'Health Unit', exact: true })).toHaveValue(/.+/);
  await openUnits();
  await create('Second Health Unit');
  const row = () => page.getByRole('row').filter({ hasText: 'Second Health Unit' });
  await row().getByRole('button', { name: 'Edit', exact: true }).click();
  await page.getByLabel('Health Unit name').fill('Renamed Health Unit');
  await page.getByRole('button', { name: 'Review changes' }).click();
  await expect(page.getByRole('alert')).toContainText('Historical records will display the new name.');
  await expect(page.getByText('Before: Second Health Unit', { exact: true })).toBeVisible();
  await expect(page.getByText('After: Renamed Health Unit', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Close dialog' }).click();
  await expect(row()).toHaveCount(1);
  await row().getByRole('button', { name: 'Edit', exact: true }).click();
  await page.getByLabel('Health Unit name').fill('Renamed Health Unit');
  await page.getByRole('button', { name: 'Review changes' }).click();
  await page.getByRole('checkbox').check();
  await page.getByRole('button', { name: 'Confirm and save changes' }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.getByRole('combobox', { name: 'Health Unit', exact: true }).getByRole('option', { name: 'Renamed Health Unit', exact: true })).toHaveCount(1);
  const selector = page.getByRole('combobox', { name: 'Health Unit', exact: true });
  await selector.selectOption({ label: 'Renamed Health Unit' });
  const renamedId = await selector.inputValue();
  await page.getByRole('button', { name: 'Announcements', exact: true }).click();
  await page.getByRole('textbox', { name: /^Facility announcement/ }).fill('Canceled announcement');
  page.once('dialog', d => d.dismiss());
  await page.getByRole('button', { name: 'Update announcement' }).click();
  expect((await db.query('SELECT announcement FROM facilities WHERE id=$1', [renamedId])).rows[0].announcement).toBe('Original announcement');
  page.once('dialog', d => d.accept());
  await page.getByRole('button', { name: 'Update announcement' }).click();
  await expect.poll(async () => (await db!.query('SELECT announcement FROM facilities WHERE id=$1', [renamedId])).rows[0].announcement).toBe('Canceled announcement');
  await page.getByRole('button', { name: 'Health Units', exact: true }).click();
  await page.getByRole('button', { name: 'Delete Renamed Health Unit', exact: true }).click();
  await page.getByRole('button', { name: 'Close dialog' }).click();
  await expect(selector.getByRole('option', { name: 'Renamed Health Unit', exact: true })).toHaveCount(1);
  await page.getByRole('button', { name: 'Delete Renamed Health Unit', exact: true }).click();
  await page.getByRole('checkbox').check();
  await page.getByRole('button', { name: 'Delete Health Unit permanently' }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(selector.getByRole('option')).toHaveText(['First Health Unit']);
  await expect.poll(() => page.evaluate(() => localStorage.getItem('quecare-facility'))).toBe(await selector.inputValue());
  const firstId = await selector.inputValue();
  const assigned = (await db.query("INSERT INTO users(name,email,password_hash,role,facility_id,disabled) VALUES('Disabled','disabled@test.local',$1,'provider',$2,true) RETURNING id", [hash, firstId])).rows[0];
  await page.reload(); await openUnits();
  await expect(page.getByRole('button', { name: 'Delete First Health Unit', exact: true })).toBeDisabled();
  await expect(page.getByText('Assigned users (including disabled accounts): 1')).toBeVisible();
  await db.query('DELETE FROM users WHERE id=$1', [assigned.id]);
  await page.reload(); await openUnits();
  await page.getByRole('button', { name: 'Delete First Health Unit', exact: true }).click();
  await page.getByRole('checkbox').check();
  await page.getByRole('button', { name: 'Delete Health Unit permanently' }).click();
  await expect(page.getByRole('heading', { name: 'No Health Units configured', level: 1 })).toBeVisible();
  await expect.poll(() => page.evaluate(() => localStorage.getItem('quecare-facility'))).toBeNull();
  await create('Recovered Health Unit');
  await expect(page.getByRole('combobox', { name: 'Health Unit', exact: true }).getByRole('option')).toHaveText(['Recovered Health Unit']);
  expect(errors).toEqual([]);
  console.log('Health Unit browser checks passed: empty-state sign-in/recovery, create, edit review/cancel/save, announcement cancel/publish, deletion blockers, deletion cancel/save, selector refresh and fallback.');
} finally {
  if (browser) await browser.close();
  if (server) await new Promise<void>((resolve, reject) => server!.close(e => e ? reject(e) : resolve()));
  if (db) await db.end();
  await root.query(`DROP SCHEMA IF EXISTS ${schema} CASCADE`); await root.end();
}
